@pytest.mark.parametrize('fixture_name, elapsed', [
    ('sap_collection_sequence_golden.json', 0),
    ('sap_collection_sequence_time_golden.json', 12),
    ('sap_collection_nonzero_golden.json', None),
    ('sap_collection_token_golden.json', None)])
def test_consecutive_sdk_signature_counters_match(fixture_name, elapsed):
    from types import SimpleNamespace

    from shopee_affiliate.sap_codec import decode_sec
    from shopee_affiliate.sap_crypto import decode_collection
    from shopee_affiliate.sap_state import decode_payload
    fixture = json.loads((Path(__file__).parent / 'fixtures' / fixture_name).read_text())
    before, after = fixture['before_headers'], fixture['target_headers']
    def vectors(headers):
        state = decode_payload(decode_sec(headers['x-sap-sec'], headers['x-sap-ri']).payload,
                               headers['x-sap-ri'])
        return [bytes.fromhex(v['hex']) for v in state['vectors']]
    old, new = vectors(before), vectors(after)
    ctx = SimpleNamespace(old_mask=old[1], new_mask=new[1], old_random=old[14],
        new_random=new[14], old_ri=before['x-sap-ri'], new_ri=after['x-sap-ri'],
        raw_url=fixture['raw_url'], timestamp_ms=fixture['timestamp_ms'], advance_request=elapsed is not None,
        request_rate=2.0 if elapsed is not None else None, elapsed_seconds=elapsed)
    for kind, data_index, check_index in (('custom', 12, 13), ('salsa', 15, 11)):
        plain = decode_collection(old[data_index], old[check_index], kind, old[1], old[14])
        target = decode_collection(new[data_index], new[check_index], kind, new[1], new[14])
        assert refresh_collection(kind, plain, ctx) == target
        if 'synthetic_token' in fixture and kind == 'salsa':
            for buffer in (plain, target):
                token = next(item['value'] for item in parse_collection(kind, buffer)
                             if item['pc'] == 36135)
                assert token == fixture['synthetic_token'].encode('ascii')


def test_serializer_rejects_unknown_schema_and_nonfinite_float():
    fields = parse_collection('custom', bytes.fromhex(GOLDEN[0]['collections']['custom']['plaintext']))
    for changed in (fields[:-1], [{**fields[0], 'pc': -1}, *fields[1:]],
                    [{**item, 'value': float('nan')} if item['type'] == 'f32' else item for item in fields]):
        with pytest.raises(ValueError):
            serialize_collection('custom', changed)


def test_parser_rejects_nonfinite_float():
    plain = bytes.fromhex(GOLDEN[0]['collections']['custom']['plaintext'])
    # First float follows two uint16 values and one byte in source layout.
    invalid = plain[:5] + bytes.fromhex('7fc00000') + plain[9:]
    with pytest.raises(ValueError, match='finite'):
        parse_collection('custom', invalid)


def test_response_completion_only_changes_two_proven_counters():
    from shopee_affiliate.sap_collections import complete_response_collection
    sample = GOLDEN[0]
    mask = bytes.fromhex(sample['mask'])
    plain = bytes.fromhex(sample['collections']['custom']['plaintext'])
    fields = parse_collection('custom', plain)
    completed = parse_collection('custom', complete_response_collection(plain, mask))
    assert [a['pc'] for a, b in zip(fields, completed) if a != b] == [36428, 37834]
    assert plain.hex() == sample['collections']['custom']['plaintext']


@pytest.mark.parametrize('pc,constant', [(36428, 2441765646), (37834, 4276226149)])
def test_response_completion_rejects_overflow(pc, constant):
    from shopee_affiliate.sap_collections import complete_response_collection
    sample = GOLDEN[0]
    mask = bytes.fromhex(sample['mask'])
    fields = parse_collection('custom', bytes.fromhex(sample['collections']['custom']['plaintext']))
    exhausted = [{**field, 'value': 0xffffffff ^ int.from_bytes(mask[:4], 'little') ^ constant}
                 if field['pc'] == pc else field for field in fields]
    with pytest.raises(ValueError, match='overflow'):
        complete_response_collection(serialize_collection('custom', exhausted), mask)


