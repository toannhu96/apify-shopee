"""Original SDK fixtures: independent binary parsing and semantic refresh."""
import json
from pathlib import Path

import pytest

from shopee_affiliate.sap_collections import (
    parse_collection,
    refresh_collection,
    serialize_collection,
)
from shopee_affiliate.sap_refresh import RefreshContext, refresh_root

GOLDEN = json.loads((Path(__file__).parent / 'fixtures/sap_collections_golden.json').read_text())


def context(target):
    original = GOLDEN[0]
    return RefreshContext(bytes.fromhex(original['mask']), bytes.fromhex(target['mask']),
        bytes.fromhex(original['random']), bytes.fromhex(target['random']),
        target['raw_url'], 1800000012345, original['ri'], target['ri'])


@pytest.mark.parametrize('sample', GOLDEN)
@pytest.mark.parametrize('kind', ['custom', 'salsa'])
def test_parse_matches_original_typed_writes(sample, kind):
    case = sample['collections'][kind]
    plain = bytes.fromhex(case['plaintext'])
    fields = parse_collection(kind, plain)
    assert serialize_collection(kind, fields) == plain
    for field, write in zip(fields, case['writes'], strict=True):
        assert field['pc'] == write['pc']
        expected = write['args'][0]
        if isinstance(expected, dict):
            expected = bytes(expected['bytes'])
        elif field['type'] != 'f32':
            expected &= (1 << (field['width'] * 8)) - 1
        assert field['value'] == expected


@pytest.mark.parametrize('target', [GOLDEN[1], GOLDEN[4]])
@pytest.mark.parametrize('kind', ['custom', 'salsa'])
def test_refresh_matches_independent_original_sdk_plaintext(target, kind):
    # Target4 pins original SDK startup seconds and device SAPid. All request
    # inputs (timestamp, RI, URL, masks) are regenerated by the original SDK.
    plain = bytes.fromhex(GOLDEN[0]['collections'][kind]['plaintext'])
    actual = refresh_collection(kind, plain, context(target))
    assert actual.hex() == target['collections'][kind]['plaintext']


@pytest.mark.parametrize('index, timestamp', [(1, 1800000000000), (4, 1800000012345)])
def test_full_headers_match_original_sdk_without_oracle_callback(index, timestamp):
    before, target = GOLDEN[0], GOLDEN[index]
    actual = refresh_root(before['headers']['x-sap-sec'], before['ri'], target['ri'],
        new_mask=bytes.fromhex(target['mask']), new_random=bytes.fromhex(target['random']),
        raw_url=target['raw_url'], timestamp_ms=timestamp,
        refresh_collection=refresh_collection, detector_padding=bytes(target['padding']))
    assert actual == target['headers']


